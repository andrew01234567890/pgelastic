    /// Forces every key into one bucket, so nothing but the comparator can tell
    /// two statements apart.
    #[derive(Debug, Clone, Default)]
    struct CollidingHasher;

    impl Hasher for CollidingHasher {
        fn finish(&self) -> u64 {
            0
        }
        fn write(&mut self, _bytes: &[u8]) {}
    }

    impl BuildHasher for CollidingHasher {
        type Hasher = Self;
        fn build_hasher(&self) -> Self {
            Self
        }
    }

    #[test]
    fn statements_with_colliding_hashes_are_still_distinct() {
        let mut cache = GlobalStatementCache::with_hasher(CollidingHasher);

        let transfer = cache.intern(key("UPDATE accounts SET balance = $1", &[20]));
        let audit = cache.intern(key("DELETE FROM audit_log WHERE id = $1", &[20]));
        let same_text_other_types = cache.intern(key("UPDATE accounts SET balance = $1", &[701]));

        assert_eq!(cache.len(), 3);
        assert_ne!(transfer.id(), audit.id());
        assert_ne!(transfer.id(), same_text_other_types.id());
        assert_ne!(transfer.name(), audit.name());

        assert_eq!(
            cache
                .get(&key("DELETE FROM audit_log WHERE id = $1", &[20]))
                .unwrap()
                .id(),
            audit.id()
        );
        assert_eq!(
            cache
                .get(&key("UPDATE accounts SET balance = $1", &[20]))
                .unwrap()
                .key()
                .query(),
            &Bytes::from_static(b"UPDATE accounts SET balance = $1")
        );
    }
