    #[test]
    fn the_least_recently_used_statement_is_evicted() {
        let mut cache = GlobalStatementCache::new();
        let mut server = ServerStatements::new(2);

        let first = cache.intern(key("SELECT 1", &[]));
        let second = cache.intern(key("SELECT 2", &[]));
        let third = cache.intern(key("SELECT 3", &[]));

        server.ensure(&first);
        server.ensure(&second);
        server.ensure(&first);

        assert_eq!(
            server.ensure(&third),
            ServerAction::EvictThenParse {
                evict: second.name().clone(),
                name: third.name().clone(),
            }
        );
        assert!(server.contains(&first));
        assert!(!server.contains(&second));
        assert_eq!(server.len(), 2);
    }

